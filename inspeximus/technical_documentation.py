def render_markdown(doc: dict, title: str = "Technical documentation skeleton (Annex IV)") -> str:
    """A readable rendering of the skeleton. Values that are dicts or lists are rendered as JSON blocks."""
    out = [f"# {title}", "",
           f"Generated {time.strftime('%Y-%m-%d %H:%M:%S', time.gmtime(doc.get('generated_at', 0)))} UTC by "
           f"inspeximus {doc.get('inspeximus_version')}. {doc.get('scope')}", "",
           f"Operator fields still to fill: {len(doc.get('operator_fields_missing', []))} of "
           f"{doc.get('operator_fields_total')}: {', '.join(doc.get('operator_fields_missing', [])) or 'none'}", ""]

    def title_of(key):
        head, _, rest = key.partition("_")
        rest = rest.replace("_", " ")
        if head.isdigit():
            return f"{head}. {rest[:1].upper()}{rest[1:]}"
        if len(head) == 1 and head.isalpha():
            return f"({head}) {rest[:1].upper()}{rest[1:]}"
        k = key.replace("_", " ")
        return k[:1].upper() + k[1:]

    def emit(key, val, level):
        out.append("#" * min(level, 6) + " " + title_of(key))
        out.append("")
        # recurse into the numbered sections and their lettered items; everything deeper is a block
        if isinstance(val, dict) and level <= 3 and "kind" not in val                 and any(isinstance(v, (dict, list)) for v in val.values()):
            for k, v in val.items():
                emit(k, v, level + 1)
            return
        if isinstance(val, (dict, list)):
            out.append("```json")
            out.append(json.dumps(val, indent=2, ensure_ascii=False, default=str))
            out.append("```")
        else:
            out.append(str(val))
        out.append("")

    for key, val in doc.get("sections", {}).items():
        emit(key, val, 2)
    out.append(f"Content hash: `{doc.get('content_sha256')}`")
    out.append("")
    return "\n".join(out)
