"""Annex IV technical documentation and Art. 13 instructions for use, generated from the evidence.

EU AI Act Art. 11 requires technical documentation for a high-risk system, and Annex IV lists its
contents. Most of Annex IV is the provider's own account: intended purpose, design choices, the risk
management system, the declaration of conformity. A memory and action ledger cannot write those.
What it can write is the evidence the account rests on: which logs exist, what they cover, how an
auditor verifies them, what the store holds, what oversight happened, what was erased. This module
fills those parts from the live store and ledger and marks every other field as operator input, so
the output is a skeleton with the evidence in place and the gaps named, never a finished document.

Art. 13(3)(f) asks the instructions for use to explain how to collect, store and interpret the logs.
`instructions_for_use()` is that section for this store: the file layout, the entry schema, the
verifier commands and the retention behaviour, written from the code that runs, not from memory.

    from inspeximus.technical_documentation import annex_iv, instructions_for_use, render_markdown

    doc = annex_iv(store, ledger=led, operator={"system_name": "Support agent", "provider": "Acme GmbH"})
    open("annex_iv.md", "w").write(render_markdown(doc))

Evidence, not a conformity assessment. Article references are to Regulation (EU) 2024/1689 as
amended by Regulation (EU) 2026/1744; check them against the Official Journal before relying on them.
"""
from __future__ import annotations

