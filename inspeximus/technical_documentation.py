from .core import __version__

__all__ = ["annex_iv", "instructions_for_use", "registration_export", "render_markdown", "OPERATOR_FIELDS",
           "REGISTRATION_FIELDS"]

OPERATOR_INPUT = "OPERATOR INPUT REQUIRED"

#: The Annex IV fields the ledger cannot fill. Each maps to the Annex IV item it belongs to.
OPERATOR_FIELDS = {
    "system_name": "1(a)", "intended_purpose": "1(a)", "provider": "1(a)", "system_version": "1(a)",
    "interaction_with_other_systems": "1(b)", "software_and_firmware_versions": "1(c)",
    "forms_placed_on_market": "1(d)", "hardware_description": "1(e)",
    "photographs_or_illustrations": "1(f)", "user_interface": "1(g)",
    "design_methods_and_third_party_tools": "2(a)", "design_specifications_and_logic": "2(b)",
    "system_architecture": "2(c)", "training_data_and_datasheets": "2(d)",
    "human_oversight_measures": "2(e)",
    "predetermined_changes": "2(f)", "validation_and_testing_procedures": "2(g)",
    "capabilities_and_limitations": "3", "performance_metrics_appropriateness": "4",
    "risk_management_system": "5", "lifecycle_changes": "6", "harmonised_standards": "7",
    "declaration_of_conformity": "8", "post_market_monitoring_plan": "9",
}


def _sha(obj: Any) -> str:
    return hashlib.sha256(json.dumps(obj, sort_keys=True, separators=(",", ":"), default=str).encode()).hexdigest()


def _safe(fn, default=None):
    try:
        return fn()
    except Exception as e:  # noqa: BLE001 - a section that cannot be read says so instead of failing the document
        return {"error": f"{type(e).__name__}: {e}"} if default is None else default


